# =========================
# Active spinner (defaults)
# =========================
SPINNER_NAME="dots"

# =========================
# Spinner loader
# =========================
load_spinner() {
  local name="$1"

  if [[ -z "${SPINNER_FRAMES[$name]}" ]]; then
    echo "Unknown spinner: $name" >&2
    return 1
  fi

  IFS=' ' read -r -a SPINNER <<< "${SPINNER_FRAMES[$name]}"
  SPINNER_DELAY="${SPINNER_DELAY[$name]}"
}
